-- 1. LEGACY ADMINS TABLE
CREATE TABLE IF NOT EXISTS admins (
  id BIGSERIAL PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. USERS TABLE
CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  designation VARCHAR(160) NOT NULL,
  role VARCHAR(16) NOT NULL DEFAULT 'USER' CHECK (role IN ('ADMIN', 'USER')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. DOCTORS TABLE
CREATE TABLE IF NOT EXISTS doctors (
  id SERIAL PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  designation VARCHAR(160) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. PRICING RATES TABLE
CREATE TABLE IF NOT EXISTS pricing_rates (
  id BIGSERIAL PRIMARY KEY,
  limb_type VARCHAR(32) NOT NULL CHECK (limb_type IN ('UNILATERAL', 'BILATERAL')),
  duration_days INTEGER NOT NULL CHECK (duration_days IN (7, 10, 14, 21)),
  volume_range NUMRANGE NOT NULL,
  financial_category INTEGER NOT NULL CHECK (financial_category IN (1, 2, 3, 4)),
  rate NUMERIC(12, 2) NOT NULL CHECK (rate >= 0),
  CONSTRAINT pricing_rates_unique_combination UNIQUE (limb_type, duration_days, volume_range, financial_category)
);

-- 5. ADDITIONAL SERVICES TABLE
CREATE TABLE IF NOT EXISTS additional_services (
  id BIGSERIAL PRIMARY KEY,
  service_name VARCHAR(160) NOT NULL UNIQUE,
  cost_per_day NUMERIC(12, 2) NOT NULL CHECK (cost_per_day >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 6. AUDIT LOGS TABLE
CREATE TABLE IF NOT EXISTS audit_logs (
  id SERIAL PRIMARY KEY,
  admin_id INTEGER NOT NULL REFERENCES users(id),
  action VARCHAR(32) NOT NULL,
  entity_type VARCHAR(32) NOT NULL,
  entity_id INTEGER NOT NULL,
  old_value JSONB,
  new_value JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at
  ON audit_logs (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_audit_logs_filters
  ON audit_logs (entity_type, action, admin_id, created_at DESC);

